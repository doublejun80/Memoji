#!/usr/bin/env node

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const args = parseArgs(process.argv.slice(2));
if (args.help) {
  process.stdout.write(`Usage: node scripts/benchmark-local-ai.mjs [options]\n\n` +
    `  --endpoint <url>  OpenAI-compatible endpoint (default: http://127.0.0.1:9379)\n` +
    `  --model <id>      Registered model id (default: gemma4-e2b)\n` +
    `  --output <path>   Write JSON evidence\n` +
    `  --strict          Return non-zero if the endpoint is unavailable\n`);
  process.exit(0);
}

const endpoint = (args.endpoint ?? 'http://127.0.0.1:9379').replace(/\/$/, '');
const model = args.model ?? 'gemma4-e2b';
const report = {
  schemaVersion: 1,
  capturedAt: new Date().toISOString(),
  environment: {
    platform: process.platform,
    arch: process.arch,
    node: process.version,
    windowsVdi: process.platform === 'win32' && args.vdi === true,
  },
  endpoint,
  model,
  status: 'running',
  matrix: [],
  limitations: [],
};

try {
  const modelsResponse = await fetch(`${endpoint}/v1/models`, { signal: AbortSignal.timeout(5_000) });
  if (!modelsResponse.ok) throw new Error(`/v1/models returned HTTP ${modelsResponse.status}`);
  const models = await modelsResponse.json();
  const ids = (models.data ?? []).map((entry) => entry.id);
  if (!ids.includes(model)) throw new Error(`Configured model is absent: ${model}`);
} catch (error) {
  report.status = 'blocked';
  report.limitations.push(`Runtime/model unavailable: ${String(error)}`);
  await finish(report, args);
  process.exit(process.exitCode ?? 0);
}

for (const promptChars of [256, 1_024]) {
  for (const maxOutputTokens of [64, 256]) {
    for (const temperatureState of ['cold-session-first-request', 'warm-repeat']) {
      const prompt = makePrompt(promptChars);
      const measurement = await measureStream({ endpoint, model, prompt, maxOutputTokens });
      report.matrix.push({
        promptChars,
        maxOutputTokens,
        state: temperatureState,
        ...measurement,
      });
    }
  }
}

report.status = report.matrix.every((row) => row.ok) ? 'passed-non-vdi' : 'failed';
if (!report.environment.windowsVdi) {
  report.limitations.push('Results describe this host only and are not Windows VDI validation.');
}
report.limitations.push('Prompt matrix is generated by Unicode character count; server-reported usage is retained when available.');
await finish(report, args);

async function measureStream({ endpoint: baseUrl, model: modelId, prompt, maxOutputTokens }) {
  const started = performance.now();
  let firstByteAt = null;
  let responseText = '';
  let usage = null;
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 180_000);
  try {
    const response = await fetch(`${baseUrl}/v1/chat/completions`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      signal: controller.signal,
      body: JSON.stringify({
        model: modelId,
        stream: true,
        stream_options: { include_usage: true },
        max_tokens: maxOutputTokens,
        temperature: 0.4,
        messages: [{ role: 'user', content: prompt }],
      }),
    });
    if (!response.ok || !response.body) {
      return { ok: false, httpStatus: response.status, error: (await response.text()).slice(0, 240) };
    }
    const reader = response.body.getReader();
    const decoder = new TextDecoder();
    let buffer = '';
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      if (firstByteAt === null) firstByteAt = performance.now();
      buffer += decoder.decode(value, { stream: true });
      const lines = buffer.split('\n');
      buffer = lines.pop() ?? '';
      for (const line of lines) {
        const payload = line.trim().replace(/^data:\s*/, '');
        if (!payload || payload === '[DONE]') continue;
        try {
          const event = JSON.parse(payload);
          responseText += event.choices?.[0]?.delta?.content ?? '';
          if (event.usage) usage = event.usage;
        } catch {
          // Ignore non-JSON keepalive lines while preserving protocol timing.
        }
      }
    }
    const ended = performance.now();
    const totalMs = ended - started;
    const completionTokens = usage?.completion_tokens ?? null;
    return {
      ok: true,
      httpStatus: response.status,
      ttftMs: firstByteAt === null ? null : Number((firstByteAt - started).toFixed(2)),
      totalMs: Number(totalMs.toFixed(2)),
      promptTokens: usage?.prompt_tokens ?? null,
      generatedTokens: completionTokens,
      decodeTokensPerSecond: completionTokens
        ? Number((completionTokens / (totalMs / 1_000)).toFixed(2))
        : null,
      outputChars: responseText.length,
    };
  } catch (error) {
    return { ok: false, error: String(error) };
  } finally {
    clearTimeout(timeout);
  }
}

function makePrompt(characterCount) {
  const prefix = '다음 로컬 우선 배포 메모를 한 문장으로 요약하세요. ';
  return `${prefix}${'가나다라마바사 아자차카타파하 '.repeat(characterCount)}`
    .slice(0, characterCount);
}

async function finish(value, parsedArgs) {
  const rendered = `${JSON.stringify(value, null, 2)}\n`;
  if (parsedArgs.output) {
    const output = resolve(parsedArgs.output);
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, rendered, 'utf8');
  }
  process.stdout.write(rendered);
  if (parsedArgs.strict && value.status !== 'passed-non-vdi' && value.status !== 'passed-vdi') {
    process.exitCode = 2;
  }
}

function parseArgs(values) {
  const parsed = {};
  for (let index = 0; index < values.length; index += 1) {
    const token = values[index];
    if (!token.startsWith('--')) continue;
    const key = token.slice(2);
    const value = values[index + 1];
    if (!value || value.startsWith('--')) parsed[key] = true;
    else {
      parsed[key] = value;
      index += 1;
    }
  }
  return parsed;
}
